def _make_fake_pdf(target: Path) -> None:
    """写一个 MZ 头（Windows 可执行文件特征）但扩展名为 .pdf —— 用于 T-01。"""
    target.write_bytes(b"MZ\x90\x00" + b"\x00" * 508 + b"This is not a real PDF.")
