def _remove_stale(keep: set[Path]) -> int:
    """删掉上一版留下的文件（例如改名前的「（演示样例）」那批）。

    只删 demo/ 与 demo/fixtures/ 一层目录里的受支持类型，
    不做递归删除——这个脚本会在别人的机器上跑，不能有"手滑删库"的可能。
    """
    removed = 0
    for folder in (DEMO_DIR, FIXTURE_DIR):
        if not folder.exists():
            continue
        for path in sorted(folder.iterdir()):
            if not path.is_file():
                continue
            if path.suffix.lower() not in (".pdf", ".docx", ".txt", ".md"):
                continue
            if path in keep:
                continue
            path.unlink()
            removed += 1
            print(f"[del] {path.relative_to(ROOT)}（上一版遗留）")
    return removed


